"""Bundle the model JSON files into app/model/model.js so the page works from file:// without fetch."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODEL = ROOT / "app" / "model"


def main() -> None:
    bundle = {name: json.loads((MODEL / f"{name}.json").read_text()) for name in ("centiles", "tracking", "breeds")}
    js = "// Generated by pipeline/05_export.py — do not edit by hand.\nwindow.DOGE_MODEL = " + json.dumps(bundle, separators=(",", ":")) + ";\n"
    (MODEL / "model.js").write_text(js)
    print("wrote", MODEL / "model.js", (MODEL / "model.js").stat().st_size, "bytes")


if __name__ == "__main__":
    main()
